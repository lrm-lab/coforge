import { COMPUTER_TERMINAL_CAPABILITY } from "@lrm/coforge-sdk/internal/computer-terminal-wire";
import { CODEX_COMPATIBLE_PROVIDER_CAPABILITY } from "@lrm/coforge-sdk/internal/codex-compatible-provider";
import { kiroEnterpriseAuthSupported } from "#src/code-agent/kiro/auth-host";
import {
  REMINDER_CAPABILITY,
  REMINDER_DUE_CAPABILITY,
  AGENT_MEMORY_CAPABILITY,
  RUNTIME_AUTH_CAPABILITY,
  RUNTIME_AUTH_STATUS_READ_CAPABILITY,
  KIRO_IDENTITY_CENTER_AUTH_CAPABILITY,
  KIRO_FREE_AUTH_CAPABILITY,
  APP_CONFIG_CAPABILITY,
  AGENT_MIGRATION_CAPABILITY,
  AGENT_TURN_INTERRUPT_CAPABILITY,
  MACHINE_STATUS_CAPABILITY,
  RELEASE_CHANNEL_CAPABILITY,
  AGENT_CONTEXT_VIEW_CAPABILITY,
  AGENT_SIDE_ASK_CAPABILITY,
  RUNTIME_MANAGE_CAPABILITY,
  AGENT_CONTROL_ACCEPTED_CAPABILITY,
  AGENT_CONFIG_CAPABILITY,
  RESET_CREDIT_CAPABILITY,
  DAEMON_AGENT_USAGE_SCAN_CAPABILITY,
} from "@lrm/coforge-sdk/internal";
import { APP_REGISTRATION_NOTICE_CAPABILITY } from "@lrm/coforge-sdk/internal/app-registration-notice";
import { AGENT_SESSION_REJECTION_CAPABILITY } from "@lrm/coforge-sdk/internal/agent-session-rejection";
import {
  PI_CHAT_CAPABILITY,
  PI_CHAT_CONTROLS_CAPABILITY,
  PI_CHAT_FILES_CAPABILITY,
  WORKBENCH_CODEX_CAPABILITY,
} from "@lrm/coforge-sdk/internal/pi-chat-wire";

/** The ready handshake advertises controls separately so older Pi chat remains usable. */
export function readyCapabilities(
  migrations: boolean,
  runtimeAuth = false,
  platform = process.platform,
  computerTerminal = false,
) {
  return [
    PI_CHAT_CAPABILITY,
    PI_CHAT_CONTROLS_CAPABILITY,
    PI_CHAT_FILES_CAPABILITY,
    WORKBENCH_CODEX_CAPABILITY,
    REMINDER_CAPABILITY,
    REMINDER_DUE_CAPABILITY,
    AGENT_MEMORY_CAPABILITY,
    APP_CONFIG_CAPABILITY,
    AGENT_TURN_INTERRUPT_CAPABILITY,
    APP_REGISTRATION_NOTICE_CAPABILITY,
    MACHINE_STATUS_CAPABILITY,
    RELEASE_CHANNEL_CAPABILITY,
    AGENT_CONTEXT_VIEW_CAPABILITY,
    AGENT_SIDE_ASK_CAPABILITY,
    RUNTIME_MANAGE_CAPABILITY,
    AGENT_CONTROL_ACCEPTED_CAPABILITY,
    AGENT_SESSION_REJECTION_CAPABILITY,
    AGENT_CONFIG_CAPABILITY,
    RESET_CREDIT_CAPABILITY,
    DAEMON_AGENT_USAGE_SCAN_CAPABILITY,
    CODEX_COMPATIBLE_PROVIDER_CAPABILITY,
    ...(runtimeAuth ? [RUNTIME_AUTH_CAPABILITY, RUNTIME_AUTH_STATUS_READ_CAPABILITY] : []),
    ...(runtimeAuth && kiroEnterpriseAuthSupported(platform)
      ? [KIRO_IDENTITY_CENTER_AUTH_CAPABILITY, KIRO_FREE_AUTH_CAPABILITY]
      : []),
    ...(migrations ? [AGENT_MIGRATION_CAPABILITY] : []),
    ...(computerTerminal ? [COMPUTER_TERMINAL_CAPABILITY] : []),
  ];
}
