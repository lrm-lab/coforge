test("an owner reopening a committed Workspace repairs failed provisioning without a second enrollment", async () => {
  const connectionString = Bun.env.CHANNEL_TEST_DATABASE_URL;
  if (!connectionString) throw new Error("CHANNEL_TEST_DATABASE_URL is required");
  const db = new PrismaClient({ adapter: new PrismaPg({ connectionString }) });
  const suffix = crypto.randomUUID().replaceAll("-", "");
  const fault = `resource_fault_${suffix}`;
  const owner = await db.user.create({
    data: { username: `recover-${suffix}`, displayName: "Accepted name", welcomedAt: new Date() },
  });
  let workspaceId: string | undefined;
  try {
    const workspace = await createOwnedWorkspace(
      db,
      { userId: owner.id, name: "Accepted name's Workspace", slug: `recover-${suffix}` },
      { id: true },
    );
    workspaceId = workspace.id;
    const computer = await db.computer.create({
      data: {
        ownerId: owner.id,
        machineId: `recover-${suffix}`,
        kind: "cloud",
        cloudSlot: "default",
        workspaces: { create: { workspaceId } },
      },
    });
    // Identifiers and the UUID literal are generated by this fixture, never external input.
    await db.$executeRawUnsafe(
      `CREATE FUNCTION ${fault}() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'fixture provisioning unavailable'; END $$`,
    );
    await db.$executeRawUnsafe(
      `CREATE TRIGGER ${fault} BEFORE INSERT ON agents FOR EACH ROW WHEN (NEW."ownerId" = '${owner.id}'::uuid) EXECUTE FUNCTION ${fault}()`,
    );
    const input = { workspaceId, userId: owner.id };
    await expect(recoverWorkspaceResourcesOnOpen(db, input)).rejects.toThrow(
      "fixture provisioning unavailable",
    );
    const accepted = await db.user.findUniqueOrThrow({ where: { id: owner.id } });
    expect(accepted.welcomedAt).not.toBeNull();
    expect(accepted.displayName).toBe("Accepted name");
    expect(await db.workspace.count({ where: { id: workspaceId } })).toBe(1);
    await db.$executeRawUnsafe(`DROP TRIGGER ${fault} ON agents`);
    await Promise.all([
      recoverWorkspaceResourcesOnOpen(db, input),
      recoverWorkspaceResourcesOnOpen(db, input),
    ]);
    const identities = async () => ({
      memory: (await db.workspaceMemoryAgent.findUniqueOrThrow({ where: { workspaceId } })).agentId,
      platform: (
        await db.workspaceAssistantSession.findUniqueOrThrow({
          where: { workspaceId_userId: input },
        })
      ).agentId,
      weekly: (
        await db.weeklyReportAssistant.findUniqueOrThrow({ where: { workspaceId_userId: input } })
      ).agentId,
    });
    const repaired = await identities();
    expect(new Set(Object.values(repaired)).size).toBe(3);
    expect(await db.agent.count({ where: { workspaceId } })).toBe(3);
    expect((await db.agent.findUniqueOrThrow({ where: { id: repaired.weekly } })).computerId).toBe(
      computer.id,
    );
    await recoverWorkspaceResourcesOnOpen(db, input);
    expect(await identities()).toEqual(repaired);
    expect(await db.workspaceMembership.count({ where: { userId: owner.id } })).toBe(1);
    const archivedAt = new Date();
    await db.agent.update({ where: { id: repaired.memory }, data: { deletedAt: archivedAt } });
    await recoverWorkspaceResourcesOnOpen(db, input);
    expect(await identities()).toEqual(repaired);
    expect(
      (await db.agent.findUniqueOrThrow({ where: { id: repaired.memory } })).deletedAt,
    ).toEqual(archivedAt);
    await db.agent.update({ where: { id: repaired.memory }, data: { deletedAt: null } });
    const deleted = await new PrismaAgentDeletionStore(db).delete({
      agentId: repaired.memory,
      workspaceId,
      deletedAt: new Date(),
      deletedByUserId: owner.id,
    });
    expect(deleted.outcome).toBe("deleted");
    await recoverWorkspaceResourcesOnOpen(db, input);
    expect(await db.workspaceMemoryAgent.count({ where: { workspaceId } })).toBe(0);
    expect(await db.agent.count({ where: { workspaceId } })).toBe(3);
  } finally {
    await db.$executeRawUnsafe(`DROP TRIGGER IF EXISTS ${fault} ON agents`);
    await db.$executeRawUnsafe(`DROP FUNCTION IF EXISTS ${fault}()`);
    if (workspaceId) await db.workspace.delete({ where: { id: workspaceId } });
    await db.computer.deleteMany({ where: { ownerId: owner.id } });
    await db.user.delete({ where: { id: owner.id } });
    await db.$disconnect();
  }
});

test("opening with a local platform Computer does not retry a refused weekly binding", async () => {
  const connectionString = Bun.env.CHANNEL_TEST_DATABASE_URL;
  if (!connectionString) throw new Error("CHANNEL_TEST_DATABASE_URL is required");
  const db = new PrismaClient({ adapter: new PrismaPg({ connectionString }) });
  const suffix = crypto.randomUUID().replaceAll("-", "");
  const owner = await db.user.create({
    data: { username: `local-recover-${suffix}`, displayName: "Accepted" },
  });
  let workspaceId: string | undefined;
  try {
    const workspace = await createOwnedWorkspace(
      db,
      { userId: owner.id, name: "Local", slug: `local-recover-${suffix}` },
      { id: true },
    );
    workspaceId = workspace.id;
    const input = { workspaceId, userId: owner.id };
    await provisionWorkspaceEnrollment(db, workspaceId, owner.id);
    const session = await new WorkspaceAssistants(db).ensure(workspaceId, owner.id);
    const computer = await db.computer.create({
      data: {
        ownerId: owner.id,
        machineId: suffix,
        kind: "local",
        workspaces: { create: { workspaceId } },
      },
    });
    await db.agent.update({ where: { id: session.agentId }, data: { computerId: computer.id } });
    const weekly = await ensureWeeklyReportAssistant(db, input);
    // A refused bind must not enter ensure again on every open (which also rewrites its label).
    await db.agent.update({
      where: { id: weekly.agentId },
      data: { displayName: "Custom unconfigured label" },
    });
    await recoverWorkspaceResourcesOnOpen(db, input);
    const unchanged = await db.agent.findUniqueOrThrow({ where: { id: weekly.agentId } });
    expect(unchanged.computerId).toBeNull();
    expect(unchanged.displayName).toBe("Custom unconfigured label");
  } finally {
    if (workspaceId) await db.workspace.delete({ where: { id: workspaceId } });
    await db.computer.deleteMany({ where: { ownerId: owner.id } });
    await db.user.delete({ where: { id: owner.id } });
    await db.$disconnect();
  }
});

test("a fully provisioned open is read-only while the assistant's introduction is pending", async () => {
  // `loadWorkspaceSwitcher` runs this on every page open and `router.invalidate`: with every
  // resource present it may issue only SELECTs, and the pending introduction's missed Start is
  // the Daemon ready recovery's job — never the loader's.
  const connectionString = Bun.env.CHANNEL_TEST_DATABASE_URL;
  if (!connectionString) throw new Error("CHANNEL_TEST_DATABASE_URL is required");
  const db = new PrismaClient({ adapter: new PrismaPg({ connectionString }) });
  const suffix = crypto.randomUUID().replaceAll("-", "");
  const owner = await db.user.create({
    data: { username: `read-recover-${suffix}`, displayName: "Accepted" },
  });
  let workspaceId: string | undefined;
  try {
    const workspace = await createOwnedWorkspace(
      db,
      { userId: owner.id, name: "Read only", slug: `read-recover-${suffix}` },
      { id: true },
    );
    workspaceId = workspace.id;
    const input = { workspaceId, userId: owner.id };
    await provisionWorkspaceEnrollment(db, workspaceId, owner.id);
    const session = await new WorkspaceAssistants(db).ensure(workspaceId, owner.id);
    const computer = await db.computer.create({
      data: {
        ownerId: owner.id,
        machineId: suffix,
        kind: "cloud",
        cloudSlot: "default",
        workspaces: { create: { workspaceId } },
      },
    });
    await db.agent.update({ where: { id: session.agentId }, data: { computerId: computer.id } });
    const weekly = await ensureWeeklyReportAssistant(db, { ...input, computerId: computer.id });
    await db.agent.update({ where: { id: weekly.agentId }, data: { computerId: computer.id } });

    const statements: string[] = [];
    const counting = new PrismaClient({
      adapter: new PrismaPg({ connectionString }),
      log: [{ emit: "event", level: "query" }],
    });
    counting.$on("query", (event: { query: string }) => statements.push(event.query));
    try {
      await recoverWorkspaceResourcesOnOpen(counting, input);
      // Guard the listener itself: the open still reads, so silence means broken capture.
      expect(statements.length).toBeGreaterThan(0);
      expect(
        statements.filter((query) =>
          /^\s*(INSERT|UPDATE|DELETE|BEGIN|COMMIT|ROLLBACK)/i.test(query),
        ),
      ).toEqual([]);
    } finally {
      await counting.$disconnect();
    }
  } finally {
    if (workspaceId) await db.workspace.delete({ where: { id: workspaceId } });
    await db.computer.deleteMany({ where: { ownerId: owner.id } });
    await db.user.delete({ where: { id: owner.id } });
    await db.$disconnect();
  }
});
